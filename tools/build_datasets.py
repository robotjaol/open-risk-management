"""Generate the synthetic datasets and write metadata with checksums.

Run: python tools/build_datasets.py
"""

import hashlib
from pathlib import Path

import yaml

from risk_lab.data import synthetic

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "datasets" / "synthetic"


def sha256_of(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_dataset(frame, name, meta):
    OUT.mkdir(parents=True, exist_ok=True)
    csv_path = OUT / f"{name}.csv"
    frame.to_csv(csv_path, index=False)
    meta = dict(meta)
    meta["name"] = name
    meta["file"] = f"datasets/synthetic/{name}.csv"
    meta["rows"] = int(len(frame))
    meta["columns"] = list(frame.columns)
    meta["sha256"] = sha256_of(csv_path)
    meta["missing_values"] = int(frame.isna().sum().sum())
    (OUT / f"{name}.yaml").write_text(yaml.safe_dump(meta, sort_keys=False))
    print("wrote", csv_path.name, len(frame), "rows")


