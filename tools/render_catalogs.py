"""Write research/paper_catalog.csv and datasets/catalog.csv. Run: python tools/render_catalogs.py"""

import csv
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent))
import build_modules  # noqa: E402
import refs  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def used_by():
    table = {}
    for spec in build_modules.all_specs():
        for key in spec["refs"]:
            table.setdefault(key, []).append(spec["module"])
    return table


def write_paper_catalog():
    usage = used_by()
    path = ROOT / "research" / "paper_catalog.csv"
    with path.open("w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["key", "kind", "year", "title", "authors", "venue", "link", "verified",
                         "verified_on", "verification_source", "doi", "doi_note", "status", "used_by_modules", "contribution"])
        for key, record in refs.REFS.items():
            writer.writerow([
                key, record["kind"], record["year"] or "", record["title"], record["authors"],
                record["venue"], record["link"] or "", "yes" if record["verified"] else "no",
                refs.VERIFIED_ON if record["verified"] else "", record["source"], refs.doi_of(key), refs.doi_note(key), record["status"],
                ";".join(usage.get(key, [])), record["contribution"],
            ])
    return path


def write_dataset_catalog():
    path = ROOT / "datasets" / "catalog.csv"
    rows = []
    cards = []
    for folder in ["synthetic", "raw", "processed"]:
        cards += sorted((ROOT / "datasets" / folder).glob("*.yaml"))
    for card in cards:
        meta = yaml.safe_load(card.read_text())
        rows.append([meta["name"], meta["kind"], meta["file"], meta["rows"], len(meta["columns"]),
                     meta["license"], meta["sha256"], meta["title"], meta.get("source_url", "generated in this repository")])
    with path.open("w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["name", "kind", "file", "rows", "columns", "license", "sha256", "title", "source"])
        writer.writerows(rows)
    return path


def write_source_register():
    usage = used_by()
    lines = [
        "# Source Register",
        "",
        "Generated by `python tools/render_catalogs.py`. Do not edit by hand. Date of checks: " + refs.VERIFIED_ON + ".",
        "",
        "Verification means the bibliographic record was matched with an independent index. A DOI is listed only when its Crossref record matched title, authors, journal, year, volume and issue. It does not mean the full text was read.",
        "",
        "## Papers, standards and books",
        "",
        "| Key | Citation | DOI or link | Verified | Used by |",
        "|---|---|---|---|---|",
    ]
    for key, record in refs.REFS.items():
        doi = refs.doi_of(key)
        where = "https://doi.org/" + doi if doi else (record["link"] or "no link")
        year = record["year"] or "year not fixed"
        cite = record["authors"] + " (" + str(year) + "). " + record["title"] + ". " + record["venue"]
        status = "yes" if record["verified"] else "NO"
        mods = ", ".join(usage.get(key, [])) or "none"
        lines.append("| " + key + " | " + cite.replace("|", "/") + " | " + where + " | " + status + " | " + mods + " |")
    lines += ["", "DOI notes:", ""]
    for key in refs.DOIS:
        if refs.doi_note(key):
            lines.append("* " + key + ": " + refs.doi_note(key))
    lines += ["", "## Datasets", "", "| Name | Kind | License | Source | Checked |", "|---|---|---|---|---|"]
    for folder in ["synthetic", "raw", "processed"]:
        for card in sorted((ROOT / "datasets" / folder).glob("*.yaml")):
            meta = yaml.safe_load(card.read_text())
            origin = meta.get("source_url", "generated in this repository")
            lines.append("| " + meta["name"] + " | " + meta["kind"] + " | " + meta["license"].split(" (")[0] + " | " + origin + " | " + str(meta.get("access_date", "generated")) + " |")
    lines += [
        "",
        "Original source of german_credit: Hofmann, H. (1994). Statlog (German Credit Data). UCI Machine Learning Repository. https://doi.org/10.24432/C5NC77. The repository copy comes from the scorecardpy package, see its card.",
        "",
    ]
    path = ROOT / "research" / "source_register.md"
    path.write_text("\n".join(lines))
    return path


if __name__ == "__main__":
    print("wrote", write_paper_catalog())
    print("wrote", write_source_register())
    print("wrote", write_dataset_catalog())
